"""Проверка извлечения финансовых показателей (report_metrics_service).

Тест не читает PDF: фикстуры повторяют структуру, которую отдаёт
reports_service после разбора реального отчёта ЛУКОЙЛа (МСФО, 6 месяцев
2026), включая «неудобные» места:
  * колонки называются «Значение 1/2», а годы лежат в строке «Примечание»;
  * в ДДС есть лишняя колонка примечаний;
  * выручка — строка-раздел без чисел, а данные — в подстатье;
  * чистая прибыль есть и «от продолжающейся деятельности», и общая
    (нужна относящаяся к акционерам);
  * баланс подписан датами («30 июня 2026»), а не периодами.

Запуск: python -m backend.tests_report_metrics
"""
from backend.services import report_metrics_service as svc

failures = 0


def check(cond, msg):
    global failures
    print(("PASS: " if cond else "FAIL: ") + msg)
    if not cond:
        failures += 1


def row(label, cells, section=False, indent=0, bold=False):
    return {
        "label": label,
        "cells": cells,
        "section": section,
        "indent": indent,
        "bold": bold,
    }


# =============================================================================
# 1. Подписи периодов
# =============================================================================
half = svc._parse_period("За 6 месяцев, 30 июня 2026", "")
check(half is not None and half.kind == "half", "полугодие распознано как half")
check(half.end.isoformat() == "2026-06-30", "конец полугодия — 30 июня 2026")
check(half.label == "2026 1п", "подпись полугодия компактная")

annual = svc._parse_period("2025", "за годы, закончившиеся 31 декабря 2025")
check(annual is not None and annual.kind == "year", "год распознан как year")
check(annual.end.isoformat() == "2025-12-31", "конец года — 31 декабря")

quarter = svc._parse_period("За 3 месяца, 30 июня 2026", "")
check(quarter is not None and quarter.kind == "quarter", "3 месяца — квартал")
check(quarter.label == "2026Q2", "квартал получил номер Q2")

balance_date = svc._parse_period("30 июня 2026 данные)", "")
check(balance_date is not None and balance_date.kind == "half",
      "дата баланса 30 июня сопоставлена с полугодием")

check(svc._parse_period("Значение 1", "отчет о прибылях и убытках") is None,
      "подпись без года не создаёт период")

# =============================================================================
# 2. Сборка колонок: ОПиУ + ДДС + баланс
# =============================================================================
tables = [
    {
        "key": "income",
        "title": "Отчет о прибылях и убытках",
        "raw_title": "Раскрываемый консолидированный отчет о прибылях и убытках",
        "units": "(в миллионах российских рублей, если не указано иное)",
        "columns": ["Показатель", "За 6 месяцев, 30 июня 2026", "За 6 месяцев, 30 июня 2025"],
        "rows": [
            row("Примечание", []),
            row("Продолжающаяся деятельность", [], section=True),
            row("Выручка", [], section=True),
            row("Выручка от реализации (включая акцизы и экспортные пошлины)",
                ["2 059 279", "1 907 603"]),
            row("Износ и амортизация", ["(204 400)", "(177 842)"]),
            row("Операционная прибыль", ["610 942", "244 030"]),
            row("Финансовые расходы", ["(22 424)", "(19 365)"]),
            row("Чистая прибыль от продолжающейся деятельности, относящаяся к: "
                "акционерам ПАО «ЛУКОЙЛ»", ["430 907", "87 526"]),
            row("Чистая прибыль, относящаяся к: акционерам ПАО «ЛУКОЙЛ»",
                ["430 907", "287 023"]),
            row("Чистая прибыль", ["440 056", "288 566"]),
            row("Прибыль на акцию, относящаяся к акционерам ПАО «ЛУКОЙЛ», "
                "на одну обыкновенную акцию (в российских рублях): "
                "базовая и разводненная", ["734,23", "456,47"]),
        ],
    },
    {
        "key": "cashflow",
        "title": "Отчет о движении денежных средств",
        "raw_title": "Раскрываемый консолидированный отчет о движении денежных "
                     "средств за 6 месяцев, закончившихся 30 июня 2026",
        "units": "(в миллионах российских рублей)",
        # Первая колонка — номера примечаний; годы в строке «Примечание».
        "columns": ["Показатель", "Значение 1", "Значение 2", "Значение 3"],
        "rows": [
            row("Примечание", [None, "2026", "2025"]),
            row("Износ и амортизация", [None, "204 400", "261 559"]),
            row("Чистые денежные средства, полученные от операционной деятельности",
                [None, "789 989", "711 568"]),
            row("Капитальные затраты", [None, "(239 137)", "(386 630)"]),
        ],
    },
    {
        "key": "balance",
        "title": "Бухгалтерский баланс",
        "raw_title": "Раскрываемый консолидированный отчет о финансовом положении",
        "units": "(в миллионах российских рублей)",
        "columns": ["Показатель", "30 июня 2026 данные)", "31 декабря 2025"],
        "rows": [
            row("Итого активы", ["5 539 283", "5 474 421"]),
            row("Итого капитал", ["3 877 976", "3 626 453"]),
            row("Краткосрочные кредиты и займы и текущая часть долгосрочной "
                "задолженности", ["81 987", "80 890"]),
            row("Долгосрочная задолженность по кредитам и займам",
                ["236 713", "237 122"]),
            row("Денежные средства и их эквиваленты", ["661 391", "543 815"]),
        ],
    },
]

columns = svc.build_columns(tables)
by_label = {column["label"]: column for column in columns}
check([column["label"] for column in columns] ==
      ["2025 1п", "2025", "2026 1п"],
      "колонки: полугодия 2025/2026 и балансовый год 2025")

h1 = by_label["2026 1п"]["values"]
check(h1["revenue"] == {"v": 2059.279, "u": "bn"},
      "выручка: миллионы переведены в млрд")
check(h1["operating_profit"] == {"v": 610.942, "u": "bn"},
      "операционная прибыль извлечена")
check(h1["ebitda"] == {"v": 815.342, "u": "bn"},
      "EBITDA = операционная прибыль + амортизация")
check(h1["net_profit"] == {"v": 430.907, "u": "bn"},
      "чистая прибыль — относящаяся к акционерам, а не промежуточная")
check(h1["eps"] == {"v": 734.23, "u": "share"},
      "прибыль на акцию не масштабируется как деньги")
check(h1["operating_cash_flow"] == {"v": 789.989, "u": "bn"},
      "операционный денежный поток из ДДС")
check(h1["capex"] == {"v": 239.137, "u": "bn"},
      "CAPEX показан положительным, как в таблице")
check(h1["fcf"] == {"v": 550.852, "u": "bn"},
      "FCF = OCF − CAPEX")
check(h1["total_assets"] == {"v": 5539.283, "u": "bn"},
      "активы из баланса приклеены к полугодию")
check(h1["debt"] == {"v": 318.7, "u": "bn"},
      "долг = краткосрочные + долгосрочные кредиты и займы")
check(h1["net_debt"] == {"v": -342.691, "u": "bn"},
      "чистый долг = долг − денежные средства")
check(h1["ebitda_margin"] == {"v": 39.5936, "u": "pct"},
      "рентабельность EBITDA посчитана")
check(h1["debt_ebitda"] == {"v": 0.3909, "u": "x"},
      "долг / EBITDA посчитан")

h1_2025 = by_label["2025 1п"]["values"]
check(h1_2025.get("revenue") == {"v": 1907.603, "u": "bn"},
      "сравнительная колонка полугодия 2025 заполнена")
check("total_assets" not in h1_2025,
      "в балансе нет 30 июня 2025 — активы не выдумываются")

year_2025 = by_label["2025"]["values"]
check(year_2025.get("total_assets") == {"v": 5474.421, "u": "bn"},
      "балансовый год 2025 создал отдельную колонку")
check(year_2025.get("net_debt") == {"v": -225.803, "u": "bn"},
      "чистый долг за 2025 посчитан по балансу")

# =============================================================================
# 3. Разбор тикеров
# =============================================================================
check(svc.canonical_symbol("SBER") == "MOEX:SBER", "тикер без префикса — MOEX")
check(svc.canonical_symbol("MOEX:LKOH") == "MOEX:LKOH", "префикс MOEX сохраняется")
check(svc.canonical_symbol("BINANCE:BTCUSDT") is None, "крипта отбрасывается")
check(svc.canonical_symbol("BTCUSDT") is None, "криптопара без префикса отбрасывается")
check(svc.canonical_symbol("SECTION:Нефть") is None, "раздел watchlist отбрасывается")

print()
if failures:
    print(f"❌ Провалено проверок: {failures}")
    raise SystemExit(1)
print("✅ Все проверки финансовых показателей пройдены")
